def get_style(style_id: str | None) -> ArchitecturalStyle:
    """Get an architectural style by ID, falling back to 'modern' if not found."""
    if not style_id:
        return ARCHITECTURAL_STYLES["modern"]
    return ARCHITECTURAL_STYLES.get(style_id, ARCHITECTURAL_STYLES["modern"])
