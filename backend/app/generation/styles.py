"""
Architectural style registry for the 3D Development Platform.

Defines 20 architectural styles with prompt enrichment, material selection,
and geometry parameters used by both procedural and AI-based generation.
"""

from dataclasses import dataclass, field


@dataclass
class ArchitecturalStyle:
    """Complete architectural style definition."""

    id: str
    name: str
    description: str
    # Materials
    facade_material: str = "concrete"
    secondary_material: str = "glass"
    roof_material: str = "roof_tile"
    color_overrides: dict = field(default_factory=dict)
    # Geometry
    preferred_roof_types: list[str] = field(default_factory=lambda: ["flat"])
    window_density: float = 0.5
    window_width: float = 1.2
    window_height: float = 1.5
    balcony_probability: float = 0.3
    cornice_enabled: bool = True
    # AI prompt modifiers
    prompt_prefix: str = ""
    prompt_suffix: str = ""
    negative_prompt: str = ""
    meshy_art_style: str = "realistic"
    # Metadata
    thumbnail_url: str | None = None
    tags: list[str] = field(default_factory=list)


