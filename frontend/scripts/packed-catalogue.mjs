/** Retain all legacy IDs, reference paths and prompts without compiling several
 * megabytes of JSON into JavaScript object literals. Three already ships this
 * small inflater; no additional browser dependency or network request is needed. */
export function packCatalogue(source, { encoding = 'base64' } = {}) {
  JSON.parse(source); // Reject invalid JSON before emitting a browser module.
  // Strip whitespace only outside strings. Re-stringifying parsed objects loses
  // signed zero, which occurs in authored model offsets and must round-trip.
  const canonical = source.replace(/("(?:\\.|[^"\\])*")|\s+/g, (_match, quoted) => quoted ?? '');
  const bytes = Buffer.from(canonical, 'utf8');
  // A fixed set of build-time profiles handles both geometry recipes and prose.
  // Only the smallest stream ships; browser decoding and authored bytes stay exact.
  const packed = [8, 6, 9, 7, 5, 4, 3, 2, 1]
    .flatMap(memLevel => [0, 1].map(strategy => deflateSync(bytes, { level: 9, memLevel, strategy })))
    .reduce((a, b) => b.length < a.length ? b : a);
  let decoder = `const bytes = Uint8Array.from(atob(${JSON.stringify(packed.toString('base64'))}), character => character.charCodeAt(0));`;
  if (encoding === 'z85') {
    const padded = new Uint8Array(Math.ceil(packed.length / 4) * 4);
    padded.set(packed);
    decoder = `// Z85 v1 / RFC32, with an exact unpadded deflate length.
const Z85_ALPHABET = ${JSON.stringify(Z85_ALPHABET)};
const bytes = (${decodeZ85.toString()})(${JSON.stringify(encodeZ85(padded))},${packed.length});`;
  }
  // Validated constant data: discard decoding only when its value is unused.
  return `import { unzlibSync, strFromU8 } from 'three/examples/jsm/libs/fflate.module.js';
export default /* @__PURE__ */ (() => {
${decoder}
return JSON.parse(strFromU8(unzlibSync(bytes)));
})();`;
}

/** Local runtime trials are DEV-only. Do not ship their discovery receipts or
 * exclusive asset dependencies in a production roster that cannot use them. */
export function productionStarter(source) {
  const roster = JSON.parse(source);
  const trials = roster.entries.filter(entry => entry.status === 'local-pilot-runtime-pending');
  const entries = roster.entries.filter(entry => entry.status !== 'local-pilot-runtime-pending');
  const removed = new Set(trials.flatMap(entry => entry.dependencies ?? []));
  const retained = new Set(entries.flatMap(entry => entry.dependencies ?? []));
  return JSON.stringify({ ...roster, entries, dependencies: roster.dependencies.filter(dep =>
    !removed.has(dep.id) || retained.has(dep.id)) });
}

/** The canonical generator emits JSON plus one fixed discovery filter. Only
 * accept that exact format: a future generator change needs a reviewed codec,
 * rather than silently losing an export or changing activation behavior. */
export function packPublishedBuildingCatalogue(input) {
  const source = input.replace(/\r\n?/g, '\n');
  const prefix = "// Generated by python -m tools.catalogue_promotion sync. Edit library.json.\nimport type { PlaceAsset } from './assetRegistry';\n\nexport const CATALOGUE_BUILDING_ASSETS: PlaceAsset[] = ";
  const suffix = ";\n\nexport const PUBLISHED_BUILDING_ASSETS = CATALOGUE_BUILDING_ASSETS.filter(\n  (asset): asset is PlaceAsset & { readiness: 'ready' } => asset.readiness === 'ready',\n);\n";
  if (!source.startsWith(prefix) || !source.endsWith(suffix)) {
    throw new Error('Unsupported generated building catalogue; review export semantics before packing');
  }
  const data = source.slice(prefix.length, -suffix.length);
  if (!Array.isArray(JSON.parse(data))) throw new Error('Expected generated building catalogue array');
  return packCatalogue(data).replace('export default ', 'export const CATALOGUE_BUILDING_ASSETS = ')
    + "\nexport const PUBLISHED_BUILDING_ASSETS = CATALOGUE_BUILDING_ASSETS.filter(asset => asset.readiness === 'ready');";
}

export function packedCatalogue() {
  return {
    name: 'cityprompt-packed-catalogue',
    apply: 'build',
    enforce: 'post',
    transform(_code, id) {
      const filename = id.replaceAll('\\', '/');
      if (filename.endsWith('/src/features/pickPlace/publishedBuildingAssets.ts')) {
        return { code: packPublishedBuildingCatalogue(readFileSync(id, 'utf8')), map: null };
      }
      if (!DATA_CATALOGUES.test(filename) && !FEATURE_CATALOGUES.test(filename) && !HANDOFF_CATALOGUES.test(filename) && !STATIC_METADATA.test(filename)) return null;
      const source = readFileSync(id, 'utf8');
      return { code: packCatalogue(filename.endsWith('/src/data/classroomStarter.json')
        ? productionStarter(source) : source, { encoding: /\/src\/data\/(?:buildingArchetypes|nativeStreetPilots)\.json$/.test(filename) ? 'z85' : 'base64' }), map: null };
    },
  };
}
